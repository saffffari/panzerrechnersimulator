"""Write the Tiger FEA parts sheet from the matcher's tags and the master's measured geometry.

    TIGER_WORK=<dir> python3 -I tools/tiger_production/sheet.py
Outputs docs/fea/tiger_parts.csv (one row per part), docs/fea/tiger_materials.csv (the material
table every part points at) and catalog/tiger_parts.v1.json (the same, keyed by game node).
Volumes are the game mesh's closed volume; mass = volume x density. Material values marked
'nominal' are generic handbook figures for the class and must be sourced before FEA use."""
import csv, json, os, re, collections
W = os.environ['TIGER_WORK']
tags = json.load(open(os.path.join(W, 'tags.json')))
geo = {p['name']: p for p in json.load(open(os.path.join(W, 'master_parts.json')))}
MAT = [  # id, density kg/m3, E GPa, Poisson, yield MPa, UTS MPa, hardness, source status
    ('armour_rolled_homogeneous', 7850, 207, 0.29, 780, 950, 'BHN ~255-300 (to source: Allied examinations of Tiger plate)', 'nominal'),
    ('steel_structural_plate', 7850, 200, 0.29, 250, 410, '', 'nominal (mild steel plate)'),
    ('steel_structural', 7850, 200, 0.29, 250, 410, '', 'nominal (mild steel)'),
    ('steel_cast', 7850, 200, 0.29, 400, 600, '', 'nominal (cast steel)'),
    ('steel_track_cast', 7900, 200, 0.29, 380, 800, 'as-cast ~200 BHN', 'nominal (manganese cast steel)'),
    ('steel_roadwheel_rubber_tyred', 7200, 200, 0.29, 300, 450, '', 'composite: steel disc + rubber tyre; split before FEA'),
    ('steel_gun', 7850, 207, 0.29, 900, 1100, '', 'nominal (gun steel)'),
    ('iron_cast_machinery', 7200, 110, 0.26, None, 250, '', 'nominal (grey cast iron)'),
    ('radiator_copper_brass', 8500, 110, 0.34, 100, 300, '', 'nominal (copper/brass core)'),
    ('steel_sheet_tank', 7850, 200, 0.29, 220, 340, '', 'nominal (sheet steel; contents not modelled)'),
    ('steel_exhaust', 7850, 200, 0.29, 250, 410, '', 'nominal'),
    ('ammunition_88mm', 3000, None, None, None, None, '', 'composite: brass case, propellant, projectile; bulk density estimate'),
    ('glass_laminated', 2500, 70, 0.22, None, 50, '', 'nominal (laminated vision block)'),
    ('copper_cable', 6000, None, None, None, None, '', 'composite: copper + insulation'),
    ('seat_steel_leather', 1500, None, None, None, None, '', 'composite'),
    ('tool_steel_wood', 3000, None, None, None, None, '', 'composite: steel head + wood haft'),
    ('hydraulic_steel_oil', 5000, None, None, None, None, '', 'composite'),
    ('lamp_steel_glass', 4000, None, None, None, None, '', 'composite'),
    ('steel_spring', 7850, 200, 0.29, 1100, 1400, '', 'nominal (spring steel)'),
    ('instrument', 3000, None, None, None, None, '', 'composite'),
]
dens = {m[0]: m[1] for m in MAT}
os.makedirs('docs/fea', exist_ok=True)
with open('docs/fea/tiger_materials.csv', 'w', newline='') as f:
    w = csv.writer(f, lineterminator='\n')
    w.writerow(['phys_material', 'density_kg_m3', 'E_GPa', 'poisson', 'yield_MPa', 'uts_MPa', 'hardness', 'source_status'])
    for m in MAT: w.writerow(['' if v is None else v for v in m])
rows, mass = [], collections.Counter()
for game, e in sorted(tags.items()):
    g = geo[game]; d = dens.get(e['phys_material'], 7850)
    kg = g['vol']*d
    mass[e['fea_group'].split(':')[0]] += kg
    rows.append(dict(game_node=game, kit_number=e.get('kit_number', ''), kit_name=e.get('kit_name', ''), kit_assembly=e.get('kit_assembly', ''),
                     kit_match=e['match'], phys_material=e['phys_material'], fea_group=e['fea_group'],
                     armour_nominal_mm=e.get('armour_nominal_mm', ''), volume_m3=round(g['vol'], 6), mass_kg=round(kg, 2),
                     centroid_m=' '.join(f'{x:.3f}' for x in g['cen']), triangles=g['tris']))
with open('docs/fea/tiger_parts.csv', 'w', newline='') as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator='\n'); w.writeheader(); w.writerows(rows)
json.dump(dict(schema='panzer.tiger-parts.v1', frame='game master Blender world metres: +x vehicle left, -y forward, +z up',
               note='generated by tools/tiger_production (match.py, sheet.py); nominal material values must be sourced before FEA use',
               materials={m[0]: dict(zip(['density_kg_m3', 'E_GPa', 'poisson', 'yield_MPa', 'uts_MPa', 'hardness', 'source_status'], m[1:])) for m in MAT},
               parts={r['game_node']: {k: v for k, v in r.items() if k != 'game_node'} for r in rows}),
          open('catalog/tiger_parts.v1.json', 'w'), indent=0)
print('parts', len(rows), 'total mass t', round(sum(mass.values())/1000, 1), {k: round(v/1000, 1) for k, v in mass.most_common()})
# The visual classes (materials.py) join the material table, so FEA and render share class names.
import importlib.util
_spec = importlib.util.spec_from_file_location('tiger_materials', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'materials.py'))
_mod = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(_mod); _mod.join_csv(os.getcwd())
