//! A true 5x7 bitmap font for small in-play text. The scalable UI font turns to noise when it is
//! drawn a few pixels high; this one is drawn dot for dot on the game's own pixel grid, each font
//! dot a whole number of internal pixels, so it stays legible at the smallest size.
use crate::renderer::Renderer;

pub const GLYPH_W: u32 = 5;
