/// The glyph for a character. Lower case is drawn as capitals; long dashes and the ellipsis
/// become a hyphen and a full stop; anything else unknown is a blank.
fn glyph(c: char) -> &'static [u8; 7] {
    let c = match c.to_ascii_uppercase() {
        '—' | '–' => '-',
        '…' => '.',
        '·' => '.',
        '{' => '(',
        '}' => ')',
        other => other,
    };
    let code = c as u32;
    if (32..96).contains(&code) { &GLYPHS[(code - 32) as usize] } else { &GLYPHS[0] }
}

/// Width in font dots of a string.
pub fn width_dots(text: &str) -> u32 {
    (text.chars().count() as u32 * ADVANCE).saturating_sub(1)
}

/// Lit horizontal runs of `text` as (column, row, length) in font dots from its top-left.
fn runs(text: &str) -> Vec<(u32, u32, u32)> {
    let mut out = Vec::new();
    for (index, c) in text.chars().enumerate() {
        let rows = glyph(c);
        for (row, bits) in rows.iter().enumerate() {
            let mut col = 0;
            while col < GLYPH_W {
                if bits & (0x10 >> col) == 0 { col += 1; continue; }
                let start = col;
                while col < GLYPH_W && bits & (0x10 >> col) != 0 { col += 1; }
                out.push((index as u32 * ADVANCE + start, row as u32, col - start));
            }
        }
    }
    out
}

/// The smallest legible dot: one internal pixel on the shipping 450-line grid, more on finer ones.
pub fn dot_pixels(internal_height: u32) -> u32 {
    ((internal_height as f32 / 450.0).round() as u32).max(1)
}

/// Draw `text` centred on `center_x` with its top at `top_y` (both 0..1 of the frame), on the
/// internal pixel grid, with a one-dot dark shadow so it reads over snow and over steel.
pub fn draw_centered(r: &mut Renderer, text: &str, center_x: f32, top_y: f32, scale: u32, color: [f32; 4]) {
    let (iw, ih) = (r.iw.max(1) as f32, r.ih.max(1) as f32);
    let dot = (dot_pixels(r.ih) * scale.max(1)) as f32;
    let left = (center_x * iw - width_dots(text) as f32 * dot * 0.5).round();
    let top = (top_y * ih).round();
    let lit = runs(text);
    for (offset, tint) in [(dot, [0.0, 0.0, 0.0, 0.75 * color[3]]), (0.0, color)] {
        for &(col, row, len) in &lit {
            r.fill_rect((left + col as f32 * dot + offset) / iw, (top + row as f32 * dot + offset) / ih,
                len as f32 * dot / iw, dot / ih, tint);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn every_glyph_fits_five_columns_and_the_letters_are_distinct() {
        for rows in GLYPHS { assert!(rows.iter().all(|bits| *bits < 0x20)); }
        let letters: Vec<_> = ('A'..='Z').chain('0'..='9').map(|c| *glyph(c)).collect();
        for (i, a) in letters.iter().enumerate() {
            assert!(a.iter().any(|bits| *bits != 0));
            for b in &letters[i + 1..] { assert_ne!(a, b); }
        }
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('—'), glyph('-'));
        assert_eq!(glyph('é'), glyph(' '));
    }
    #[test]
    fn runs_cover_exactly_the_lit_dots_and_width_counts_the_gaps() {
        assert_eq!(width_dots(""), 0);
        assert_eq!(width_dots("A"), 5);
        assert_eq!(width_dots("AB"), 11);
        let lit: u32 = runs("T").iter().map(|run| run.2).sum();
        assert_eq!(lit, 5 + 6);
        // The second character starts one advance along.
        assert!(runs("IT").iter().any(|&(col, row, len)| (col, row, len) == (6, 0, 5)));
        assert_eq!(dot_pixels(450), 1);
        assert_eq!(dot_pixels(900), 2);
        assert_eq!(dot_pixels(360), 1);
    }
}
